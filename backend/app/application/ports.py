"""Порты (интерфейсы) слоя application. Реализуются в infrastructure.

Use cases зависят только от этих протоколов — не от SQLAlchemy или FastAPI.
"""
from __future__ import annotations

from dataclasses import dataclass
from datetime import date, datetime
from typing import Protocol, Sequence

from app.domain.entities import (
    Address,
    Direction,
    Notification,
    Order,
    OrderStatus,
    Product,
    Shop,
    ShopOrder,
    Ticket,
    User,
    Wave,
)


@dataclass(frozen=True)
class ProductFilter:
    regions: Sequence[str] = ()
    categories: Sequence[str] = ()
    query: str = ""
    min_price: int | None = None
    max_price: int | None = None
    include_inactive: bool = False
    shop_id: int | None = None


class ProductRepository(Protocol):
    def list(self, f: ProductFilter) -> list[Product]: ...
    def get(self, product_id: str) -> Product | None: ...
    def get_many(self, ids: Sequence[str]) -> dict[str, Product]: ...
    def save(self, product: Product) -> None: ...
    def delete(self, product_id: str) -> None: ...
    def ids_with_prefix(self, prefix: str) -> list[str]: ...


class WaveRepository(Protocol):
    def list(self, direction: Direction | None = None) -> list[Wave]: ...
    def get(self, wave_id: str) -> Wave | None: ...
    def existing_ids(self) -> set[str]: ...
    def add(self, wave: Wave) -> None: ...
    def save(self, wave: Wave) -> None: ...
    def orders_weight(self) -> dict[str, float]:
        """Суммарный вес активных (не отменённых) заказов по волнам."""
        ...


class OrderRepository(Protocol):
    def next_number(self) -> int: ...
    def add(self, order: Order) -> None: ...
    def save(self, order: Order) -> None: ...
    def get(self, number: int) -> Order | None: ...
    def list(self, *, status: OrderStatus | None = None, wave_id: str | None = None) -> list[Order]: ...
    def by_user(self, user_id: int) -> list[Order]: ...
    def has_product(self, product_id: str) -> bool: ...


class UserRepository(Protocol):
    def get(self, user_id: int) -> User | None: ...
    def by_phone(self, phone_digits: str) -> User | None: ...
    def by_link_token(self, token: str) -> User | None: ...
    def by_chat(self, chat_id: int) -> User | None:
        """Аккаунт, к которому привязан Telegram (покупатель приоритетнее администратора)."""
        ...
    def admins(self) -> list[User]: ...
    def customers(self) -> list[User]: ...
    def of_shop(self, shop_id: int) -> list[User]: ...
    def add(self, user: User) -> None:
        """Сохраняет нового пользователя и проставляет ему id."""
        ...
    def save(self, user: User) -> None: ...


class AddressRepository(Protocol):
    def of_user(self, user_id: int) -> list[Address]: ...
    def get(self, address_id: int) -> Address | None: ...
    def add(self, a: Address) -> None: ...
    def save(self, a: Address) -> None: ...
    def delete(self, address_id: int) -> None: ...


class NotificationRepository(Protocol):
    def add(self, n: Notification) -> None: ...
    def of_user(self, user_id: int, limit: int = 100) -> list[Notification]: ...
    def mark_read(self, user_id: int, ids: list[int] | None = None) -> None:
        """ids=None — все уведомления пользователя."""
        ...


class TicketRepository(Protocol):
    def add(self, t: Ticket) -> None:
        """Сохраняет новое обращение и проставляет номер и дату."""
        ...
    def get(self, number: int) -> Ticket | None: ...
    def save(self, t: Ticket) -> None: ...
    def list(self, user_id: int | None = None) -> list[Ticket]: ...


class ShopRepository(Protocol):
    def get(self, shop_id: int) -> Shop | None: ...
    def list(self) -> list[Shop]: ...
    def add(self, s: Shop) -> None: ...
    def save(self, s: Shop) -> None: ...


class ShopOrderRepository(Protocol):
    def get(self, order_number: int, shop_id: int) -> ShopOrder | None: ...
    def of_shop(self, shop_id: int) -> list[ShopOrder]: ...
    def of_order(self, order_number: int) -> list[ShopOrder]: ...
    def save(self, s: ShopOrder) -> None: ...


class UnitOfWork(Protocol):
    products: ProductRepository
    waves: WaveRepository
    orders: OrderRepository
    users: UserRepository
    addresses: AddressRepository
    notifications: NotificationRepository
    tickets: TicketRepository
    shops: ShopRepository
    shop_orders: ShopOrderRepository

    def __enter__(self) -> "UnitOfWork": ...
    def __exit__(self, *exc) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...


class Clock(Protocol):
    def today(self) -> date: ...
    def now(self) -> datetime: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, password_hash: str) -> bool: ...


@dataclass(frozen=True)
class SignedUpload:
    upload_url: str   # куда браузер отправляет файл (PUT)
    public_url: str   # постоянная ссылка на картинку


class ImageStorage(Protocol):
    def signed_upload(self, path: str, content_type: str) -> SignedUpload: ...


class Notifier(Protocol):
    """Доставка уведомлений (Telegram). Ошибки не пробрасываются — уведомление не должно ломать сценарий."""
    def send(self, chat_id: int, text: str, link: str | None = None, button: str = "Открыть") -> None:
        """link — страница сайта, которую откроет кнопка button под сообщением (в Telegram — как Mini App)."""
        ...
